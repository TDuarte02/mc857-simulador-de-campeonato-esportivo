// API address and key for Android and iOS, which call the API Gateway directly.
// Each one is read from a Gradle property (-PapiBaseUrl=..., -PapiKey=...), then
// from local.properties (api.baseUrl, api.key). The key is never committed: put
// it in local.properties. The web app calls /api on its own host instead, and the
// host adds the key (webpack.config.d/apiProxy.js locally, netlify/ in production).
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.reader()?.use { load(it) }
}
fun apiSetting(gradleName: String, localName: String, default: String): String =
    providers.gradleProperty(gradleName).orNull
        ?: localProperties.getProperty(localName)
        ?: default

val apiBaseUrl = apiSetting("apiBaseUrl", "api.baseUrl", "https://6cpiwkgj2d.execute-api.us-east-2.amazonaws.com/v1")
    .trimEnd('/')
val apiKey = apiSetting("apiKey", "api.key", "")
if (apiKey.isEmpty()) logger.warn("w: api.key is not set in local.properties; the API will answer 403.")

/** Writes the actual apiBaseUrl/apiKey for [sourceSet] (androidMain or iosMain). */
fun registerApiConfigTask(sourceSet: String) = tasks.register("generateApiConfig${sourceSet.removeSuffix("Main").replaceFirstChar { it.uppercase() }}") {
    val outputDir = layout.buildDirectory.dir("generated/apiConfig/$sourceSet/kotlin")
    val fileName = "ApiConfig.${sourceSet.removeSuffix("Main")}.kt"
    val baseUrl = apiBaseUrl
    val key = apiKey
    inputs.property("apiBaseUrl", baseUrl)
    inputs.property("apiKey", key)
    outputs.dir(outputDir)
    doLast {
        fun literal(value: String) = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = outputDir.get().file("com/mc857/copaamerica/platform/$fileName").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by composeApp/build.gradle.kts from local.properties. Do not edit.
            |package com.mc857.copaamerica.platform
            |
            |actual val apiBaseUrl: String = ${literal(baseUrl)}
            |
            |actual val apiKey: String = ${literal(key)}
            |""".trimMargin(),
        )
    }
}
